import Foundation

/// Builds the small `.app` that stands in for a Windows program in Finder, Launchpad and the
/// Dock. The app holds no Wine code: its executable is a one-line script that opens a
/// `finewine://launch` link, which the running FineWine app handles.
public struct ShortcutAppBuilder {
    public static let bundleIDPrefix = "io.github.stoicswe.FineWine.shortcut."
    /// Info.plist key that marks a bundle as one of ours and records what it launches.
    public static let markerKey = "FineWineShortcut"

    public let directory: URL
    private let fm = FileManager.default

    public init(directory: URL) { self.directory = directory }

    /// A shortcut FineWine made earlier, read back from its Info.plist.
    public struct Shortcut: Equatable, Sendable {
        public var url: URL
        public var prefixID: UUID
        public var programID: UUID
    }

    /// Creates (or replaces) the shortcut for `program` and returns its location. `icon` is
    /// `.icns` data; without it the shortcut gets the system's generic app icon.
    @discardableResult
    public func build(for program: Program, in prefix: Prefix, icon: Data?) throws -> URL {
        try fm.createDirectory(at: directory, withIntermediateDirectories: true)

        // Replace this program's own shortcut if it has one; otherwise pick a free name.
        let existing = list().first { $0.programID == program.id }
        let app = existing?.url ?? freeURL(for: program.name)
        let staging = directory.appendingPathComponent(".building-\(UUID().uuidString).app", isDirectory: true)
        let contents = staging.appendingPathComponent("Contents", isDirectory: true)
        let macOS = contents.appendingPathComponent("MacOS", isDirectory: true)
        let resources = contents.appendingPathComponent("Resources", isDirectory: true)
        try fm.createDirectory(at: macOS, withIntermediateDirectories: true)
        try fm.createDirectory(at: resources, withIntermediateDirectories: true)

        do {
            let link = LaunchURL.launch(prefix: prefix.id, program: program.id).url.absoluteString
            let script = "#!/bin/sh\n# Generated by FineWine. Starts “\(Self.oneLine(program.name))”.\nexec /usr/bin/open '\(link)'\n"
            let executable = macOS.appendingPathComponent("launcher")
            try Data(script.utf8).write(to: executable)
            try fm.setAttributes([.posixPermissions: 0o755], ofItemAtPath: executable.path)

            var plist: [String: Any] = [
                "CFBundleName": program.name,
                "CFBundleDisplayName": program.name,
                "CFBundleExecutable": "launcher",
                "CFBundleIdentifier": Self.bundleIDPrefix + program.id.uuidString.lowercased(),
                "CFBundlePackageType": "APPL",
                "CFBundleInfoDictionaryVersion": "6.0",
                "CFBundleShortVersionString": "1.0",
                "CFBundleVersion": "1",
                // The stub only hands off to FineWine, so it never needs a Dock icon of its own.
                "LSUIElement": true,
                Self.markerKey: ["prefix": prefix.id.uuidString, "program": program.id.uuidString,
                                 "prefixName": prefix.name]
            ]
            if let icon {
                try icon.write(to: resources.appendingPathComponent("AppIcon.icns"))
                plist["CFBundleIconFile"] = "AppIcon"
            }
            let data = try PropertyListSerialization.data(fromPropertyList: plist, format: .xml, options: 0)
            try data.write(to: contents.appendingPathComponent("Info.plist"))

            if fm.fileExists(atPath: app.path) { try fm.removeItem(at: app) }
            try fm.moveItem(at: staging, to: app)
        } catch {
            try? fm.removeItem(at: staging)
            throw error
        }
        return app
    }

    /// Every FineWine shortcut in the folder.
    public func list() -> [Shortcut] {
        let apps = ((try? fm.contentsOfDirectory(at: directory, includingPropertiesForKeys: nil)) ?? [])
            .filter { $0.pathExtension == "app" }
        return apps.compactMap(Self.read(shortcut:))
    }

    public static func read(shortcut url: URL) -> Shortcut? {
        guard let data = try? Data(contentsOf: url.appendingPathComponent("Contents/Info.plist")),
              let plist = try? PropertyListSerialization.propertyList(from: data, format: nil) as? [String: Any],
              let marker = plist[markerKey] as? [String: Any],
              let prefix = (marker["prefix"] as? String).flatMap(UUID.init(uuidString:)),
              let program = (marker["program"] as? String).flatMap(UUID.init(uuidString:)) else { return nil }
        return Shortcut(url: url, prefixID: prefix, programID: program)
    }

    /// Removes the shortcut for one program, if there is one.
    public func remove(programID: UUID) throws {
        for shortcut in list() where shortcut.programID == programID {
            try fm.removeItem(at: shortcut.url)
        }
    }

    /// Removes every shortcut that belongs to a prefix; returns how many were removed.
    @discardableResult
    public func removeAll(prefixID: UUID) throws -> Int {
        let mine = list().filter { $0.prefixID == prefixID }
        for shortcut in mine { try fm.removeItem(at: shortcut.url) }
        return mine.count
    }

    // MARK: Names

    /// A name Finder accepts: no slashes or colons, no leading dot, not empty.
    static func sanitizedName(_ raw: String) -> String {
        var name = oneLine(raw)
            .replacingOccurrences(of: "/", with: "-")
            .replacingOccurrences(of: ":", with: "-")
            .trimmingCharacters(in: .whitespaces)
        while name.hasPrefix(".") { name.removeFirst() }
        if name.isEmpty { name = "Windows Program" }
        return String(name.prefix(100))
    }

    static func oneLine(_ text: String) -> String {
        text.components(separatedBy: .newlines).joined(separator: " ")
    }

    /// `Name.app`, or `Name 2.app` and so on when that name is taken.
    private func freeURL(for name: String) -> URL {
        let base = Self.sanitizedName(name)
        var candidate = directory.appendingPathComponent(base + ".app", isDirectory: true)
        var n = 2
        while fm.fileExists(atPath: candidate.path) {
            candidate = directory.appendingPathComponent("\(base) \(n).app", isDirectory: true)
            n += 1
        }
        return candidate
    }
}
